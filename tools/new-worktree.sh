#!/usr/bin/env bash
# Create a parallel-work worktree of hsg-jinks with its own devcontainer
# instance: allocates a free host port pair, writes the per-worktree config
# (.env + .devcontainer/.env), copies in the baseline USWDS profile xar,
# builds + starts the container on the joewiz/hsg-project:v2 baseline image
# (data and libraries baked in, theme autodeploys -- see README "Baseline
# image"), then deploys the worktree's app over the image's own build (see
# .devcontainer/init.sh and README "Container initialization").
#
# Usage:
#   tools/new-worktree.sh <slug> [branch] [base]
#       new branches are based on <base> (default: main), NOT on whatever
#       the main clone has checked out
#   tools/new-worktree.sh --no-container <slug> [branch] [base]
#                                              stop after writing config files
#
# Slug convention: <type>-<wp#>-<short-slug>, e.g. fix-1217-page-box-sidebar-pages
# (<wp#> is the OpenProject work package number; omit it for untracked/ad-hoc
# work, e.g. chore-parallel-worktrees). <type> is one of feat/fix/chore/explore/
# docs/refactor/test/perf/build/port and sets the default branch's prefix
# (<type>/<rest>). An absent/unrecognized type (and so also an absent wp#,
# since it's just part of <rest>) means the slug is used as the branch name
# verbatim, with no prefix inserted (e.g. hsg-analysis).
# See README "Parallel worktrees" for the full rule.
#
# Layout rule: worktrees are FLAT SIBLINGS of the main clone
# (<parent>/<slug>), nested one level under the repos root that
# also holds hsg-jinks-data and hsg-project (<repos_root>/hsg-jinks/*). So
# from inside a worktree, ../../hsg-jinks-data and ../../hsg-project are the
# working relative references. See README "Parallel worktrees".
#
# Shared machine-local state (never in git): ~/.config/hsg/
#   worktree-ports.tsv                    slug <tab> http <tab> https <tab> path
#   xars/profile-theme-uswds-baseline.xar frozen theme baseline (see README)
# The FRUS data comes with the base image (README "Baseline image").

set -euo pipefail

CONFIG_DIR="$HOME/.config/hsg"
REGISTRY="$CONFIG_DIR/worktree-ports.tsv"
BASELINE_XAR="$CONFIG_DIR/xars/profile-theme-uswds-baseline.xar"
BASE_HTTP=8090   # main's ports; worktrees allocate upward from +1
BASE_HTTPS=8453

no_container=0
if [ "${1:-}" = "--no-container" ]; then no_container=1; shift; fi
slug="${1:?usage: tools/new-worktree.sh [--no-container] <slug> [branch] [base]}"
case "$slug" in
    feat-*|fix-*|chore-*|explore-*|docs-*|refactor-*|test-*|perf-*|build-*|port-*)
        default_branch="${slug%%-*}/${slug#*-}" ;;
    *)
        default_branch="$slug" ;;
esac
branch="${2:-$default_branch}"
base="${3:-main}"

case "$slug" in
    *[!a-zA-Z0-9._-]*) echo "error: slug must be [a-zA-Z0-9._-]" >&2; exit 1 ;;
esac

# Resolve main clone + parent dir from wherever this script's checkout lives.
script_repo=$(cd "$(dirname "$0")/.." && pwd)
common_dir=$(git -C "$script_repo" rev-parse --path-format=absolute --git-common-dir)
main_clone=$(dirname "$common_dir")
parent=$(dirname "$main_clone")
wt_path="$parent/$slug"

[ -e "$wt_path" ] && { echo "error: $wt_path already exists" >&2; exit 1; }
mkdir -p "$CONFIG_DIR/xars"
[ -f "$REGISTRY" ] || printf 'main\t%s\t%s\t%s\n' "$BASE_HTTP" "$BASE_HTTPS" "$main_clone" > "$REGISTRY"

port_taken() { # $1 = port: taken if registered or something LISTENs on it
    cut -f2,3 "$REGISTRY" | tr '\t' '\n' | grep -qx "$1" && return 0
    lsof -nP -iTCP:"$1" -sTCP:LISTEN >/dev/null 2>&1
}

n=1
while port_taken $((BASE_HTTP + n)) || port_taken $((BASE_HTTPS + n)); do
    n=$((n + 1))
    [ $n -gt 100 ] && { echo "error: no free port pair found" >&2; exit 1; }
done
http_port=$((BASE_HTTP + n)); https_port=$((BASE_HTTPS + n))

[ -f "$BASELINE_XAR" ] || {
    echo "error: baseline profile xar missing: $BASELINE_XAR" >&2
    echo "build it from the profile checkout (README 'USWDS profile baseline')" >&2
    exit 1
}

echo "==> worktree $wt_path (branch $branch, ports $http_port/$https_port)"
if git -C "$main_clone" show-ref --verify --quiet "refs/heads/$branch"; then
    git -C "$main_clone" worktree add "$wt_path" "$branch"
else
    git -C "$main_clone" worktree add "$wt_path" -b "$branch" "$base"
fi

printf '%s\t%s\t%s\t%s\n' "$slug" "$http_port" "$https_port" "$wt_path" >> "$REGISTRY"

cat > "$wt_path/.env" <<EOF
# Generated by tools/new-worktree.sh -- this worktree's own eXist instance.
# NEVER point this at host port 8080: that is the read-only hsg-shell mirror.
EXISTDB_SERVER=http://127.0.0.1:$http_port/exist
EXISTDB_USER=admin
EXISTDB_PASS=
CYPRESS_BASE_URL=http://localhost:$http_port/exist/apps/hsg-jinks
EOF

cat > "$wt_path/.devcontainer/.env" <<EOF
# Generated by tools/new-worktree.sh (see env.template)
HSG_HTTP_PORT=$http_port
HSG_HTTPS_PORT=$https_port
COMPOSE_PROJECT_NAME=hsg-jinks--$slug
EOF

cat > "$wt_path/.existdb.json" <<EOF
{
  "servers": {
    "localhost": {
      "server": "http://127.0.0.1:$http_port/exist",
      "user": "admin",
      "password": "",
      "root": "/db/apps/hsg-jinks"
    }
  },
  "sync": {
    "server": "localhost",
    "polling": false,
    "interval": 500,
    "ignore": [
      ".existdb.json",
      ".devcontainer/**",
      ".vscode/**",
      "build.sh",
      ".env",
      ".git/**",
      "components/**",
      "node_modules/**",
      "bower_components/**",
      "build/**",
      "webtest/**",
      ".moderne/**"
    ]
  }
}
EOF

cp "$BASELINE_XAR" "$wt_path/.devcontainer/profile-theme-uswds-baseline.xar"

echo "==> npm ci"
(cd "$wt_path" && npm ci --no-audit --no-fund)

if [ "$no_container" = 1 ]; then
    echo "==> --no-container: done. Start later with:"
    echo "    docker compose -f $wt_path/.devcontainer/docker-compose.yml up -d --build"
    exit 0
fi

compose() { docker compose -f "$wt_path/.devcontainer/docker-compose.yml" "$@"; }

echo "==> building + starting container (first build can take a while)"
compose up -d --build

echo "==> waiting for eXist on :$http_port"
for _ in $(seq 1 120); do
    curl -fso /dev/null "http://127.0.0.1:$http_port/exist/" && break
    sleep 5
done
curl -fso /dev/null "http://127.0.0.1:$http_port/exist/" || {
    echo "error: eXist did not come up on :$http_port" >&2; exit 1
}

cd "$wt_path"

# No `jinks create` here: this is a Mode B repo, so config.json's generated
# output (context.json, .jinks.json, .jinks-versions.json, modules/,
# templates/...) is already committed to git. `jinks create` would just
# redeploy that same content through the same deploy mechanism a plain xar
# install already uses -- and calling it first actively breaks the plain
# install that follows (repo:install-and-deploy-from-db silently drops files
# when run against an already-registered package; see init.sh). Only run
# `jinks update` by hand, and only after actually editing config.json.
#
# This is the same init.sh a later manual container recreation must be
# re-run by hand (README "Container initialization") -- one seed path, not
# two to drift.
echo "==> running init.sh (tei group membership, build + install full app xar)"
compose exec -T existdb sh /workspaces/hsg-jinks/.devcontainer/init.sh

cat <<EOF

==> done: $wt_path
    branch    $branch
    app       http://localhost:$http_port/exist/apps/hsg-jinks
    eXist     http://127.0.0.1:$http_port/exist  (HTTPS :$https_port)
    container docker compose -f .devcontainer/docker-compose.yml ps
    cypress   dotenv -e .env -- npx cypress run   (exports CYPRESS_BASE_URL)

Teardown:
    docker compose -f $wt_path/.devcontainer/docker-compose.yml down
    git -C $main_clone worktree remove $wt_path
    then delete its row from $REGISTRY
EOF
